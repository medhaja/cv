// Renders the Phosphor icons the site uses into one sprite (public/img/icons.svg).
// Re-run after adding an icon: node scripts/build-icon-sprite.mjs
import { writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as P from "@phosphor-icons/react/dist/ssr";

const ICONS = {
  "arrow-up-right": ["ArrowUpRightIcon", "bold"],
  "arrow-right": ["ArrowRightIcon", "bold"],
  wrench: ["WrenchIcon", "duotone"],
  cube: ["CubeIcon", "duotone"],
  brain: ["BrainIcon", "duotone"],
  warning: ["WarningIcon", "duotone"],
  "users-three": ["UsersThreeIcon", "duotone"],
  stack: ["StackIcon", "duotone"],
  "shield-check": ["ShieldCheckIcon", "duotone"],
  plugs: ["PlugsIcon", "duotone"],
  "hand-palm": ["HandPalmIcon", "duotone"],
  "graduation-cap": ["GraduationCapIcon", "duotone"],
  "flow-arrow": ["FlowArrowIcon", "duotone"],
  database: ["DatabaseIcon", "duotone"],
  compass: ["CompassIcon", "duotone"],
  code: ["CodeIcon", "duotone"],
  "cloud-arrow-up": ["CloudArrowUpIcon", "duotone"],
  "arrow-counter-clockwise": ["ArrowCounterClockwiseIcon", "duotone"],
};

let out = '<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Phosphor Icons (MIT), https://phosphoricons.com. Generated by scripts/build-icon-sprite.mjs -->\n';
for (const [id, [name, weight]] of Object.entries(ICONS)) {
  const markup = renderToStaticMarkup(createElement(P[name], { weight }));
  const inner = markup.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "").replace(/<rect width="256" height="256" fill="none"\/>/, "");
  out += `<symbol id="${id}" viewBox="0 0 256 256" fill="currentColor">${inner}</symbol>\n`;
}
out += "</svg>\n";
writeFileSync("public/img/icons.svg", out);
console.log("icons.svg", out.length, "bytes,", Object.keys(ICONS).length, "icons");
